"""Independent pool reconstruction and exact checks; does not import search/CP kernels."""
import hashlib,importlib.util,json,os,pathlib,sys,time
ROOT=pathlib.Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location("audit_protected_descendants",ROOT/"protected/verify_descendants.py")
D=importlib.util.module_from_spec(spec);spec.loader.exec_module(D)
def pool_hash(pool):
 return hashlib.sha256(b"".join(w.to_bytes(4,"big") for w in sorted(pool))).hexdigest()
def has_clique(adj,target):
 # Independent exact maximum-clique decision on the compatibility graph.
 n=len(adj);nodes=0
 def visit(P,size):
  nonlocal nodes
  nodes+=1
  if size>=target:return True
  if P.bit_count()+size<target:return False
  # Greedy proper coloring of compatibility graph gives an upper bound.
  order=[];bounds=[];left=P;color=0
  while left:
   color+=1;available=left
   while available:
    bit=available&-available;v=bit.bit_length()-1
    order.append(v);bounds.append(color);left^=bit;available^=bit;available&=~adj[v]
  for i in range(len(order)-1,-1,-1):
   if size+bounds[i]<target:return False
   v=order[i];bit=1<<v
   if visit(P&adj[v],size+1):return True
   P&=~bit
  return False
 return visit((1<<n)-1,0),nodes
def main():
 start=time.perf_counter();out=ROOT/"artifacts/phase2/conflict_repairs"
 report=json.loads((out/"report.json").read_text())
 words=(ROOT/"artifacts/best_code.txt").read_text().splitlines()
 accepted=D.verify(words);assert accepted["valid"]
 code=sorted(int(w,2) for w in words);owner={}
 for i,w in enumerate(code):
  for d in D.descendants(format(w,"016b")):
   assert d not in owner;owner[d]=1<<i
 # All 65536 candidate descendant sets are generated by the protected string implementation.
 descendants=[];blockers=[]
 for w in range(65536):
  ds=set(D.descendants(format(w,"016b")));descendants.append(ds);m=0
  for d in ds:m|=owner.get(d,0)
  blockers.append(m)
 code_index={w:i for i,w in enumerate(code)};rows=[];certificates=0;exact=0
 for row in report["rows"]:
  removed=set(row["removed"]);fixed=set(row["fixed_outside"]);pool=set(row["candidate_pool"])
  assert removed.isdisjoint(fixed) and removed|fixed==set(code)
  mask=sum(1<<code_index[w] for w in removed)
  reconstructed={w for w,m in enumerate(blockers) if not m&~mask}
  assert pool==reconstructed,(row["id"],"incomplete pool")
  assert pool_hash(pool)==row["candidate_pool_sha256"]
  assert row["target"]==len(removed)+1
  assert report["metadata"]["incumbent_witness_sha256"]==accepted["witness_sha256"]
  nodes=None
  if row["status"]=="INFEASIBLE_BY_VERIFIED_MATCHING_COVER":
   proof=row["proof_artifact"];new=pool-removed
   assert {e["new"] for e in proof}==new
   assert len({e["old"] for e in proof})==len(proof)==len(new)
   for e in proof:
    assert e["old"] in removed
    assert e["shared_descendant"] in descendants[e["old"]]&descendants[e["new"]]
   certificates+=1
  else:
   # Independently re-solve the full recorded pool without OR-Tools.
   pp=sorted(pool);adj=[]
   for i,w in enumerate(pp):
    adj.append(sum(1<<j for j,v in enumerate(pp) if i!=j and descendants[w].isdisjoint(descendants[v])))
   feasible,nodes=has_clique(adj,row["target"])
   assert not feasible,(row["id"],"independent feasible repair")
   exact+=1
  rows.append({"id":row["id"],"candidate_pool_sha256":row["candidate_pool_sha256"],
   "complete_full_universe_pool":True,"matching_certificate_verified":nodes is None,
   "independent_exact_nodes":nodes,"no_target_repair":True})
 result={"status":"passed","source_sha":os.environ.get("GITHUB_SHA"),"incumbent_witness_sha256":accepted["witness_sha256"],
  "independent_descendant_generator":"protected string verifier, unchanged",
  "search_code_imported":False,"cp_sat_imported":False,"full_universe_words":65536,
  "complete_pools_reconstructed":len(rows),"matching_certificates_verified":certificates,
  "other_pools_exactly_rechecked":exact,"rows":rows,"wall_seconds":time.perf_counter()-start,
  "scope":"Only the 512 explicit fixed-outside/candidate-pool repairs, not all radius-5..12 exchanges."}
 (out/"independent_audit.json").write_text(json.dumps(result,indent=2))
 print("CERTIFICATE_AUDIT "+json.dumps({k:v for k,v in result.items() if k!="rows"}),flush=True)
if __name__=="__main__":main()
